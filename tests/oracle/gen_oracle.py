#!/usr/bin/env python3
"""Differential-test oracle built from the reference implementation.

Extracts `callAPOE()` and `apoeDose()` from Biomedical-Genetics/apoe-genotyper
(scripts/apoe-genotyper.py) with `ast` -- no code is copied and PyVCF is not
needed -- runs them over every biallelic GT combination, and writes:

  tests/data/oracle_gt_combos_hg38.vcf   one sample per GT combination
  tests/data/oracle_expected.tsv         the reference script's APOE call and doses

Combinations the reference script cannot handle (it raises on mixed phased /
unphased GTs and on partially missing phased GTs) are listed as comments in
the expected file and excluded from the VCF.

Usage:
  python3 tests/oracle/gen_oracle.py /path/to/apoe-genotyper/scripts/apoe-genotyper.py
"""

import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

UNPHASED = ["0/0", "0/1", "1/0", "1/1", "./."]
PHASED = ["0|0", "0|1", "1|0", "1|1", ".|."]


def load_reference(path):
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), filename=path)
    wanted = {"callAPOE", "apoeDose"}
    funcs: list[ast.stmt] = [
        n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in wanted
    ]
    if {getattr(f, "name", None) for f in funcs} != wanted:
        sys.exit(f"could not find {sorted(wanted)} in {path}")
    module = ast.Module(body=funcs, type_ignores=[])
    namespace = {}
    exec(compile(module, path, "exec"), namespace)
    return namespace["callAPOE"], namespace["apoeDose"]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    call_apoe, apoe_dose = load_reference(sys.argv[1])

    combos = [(a, b) for group in (UNPHASED, PHASED) for a in group for b in group]
    combos += [(a, b) for a in UNPHASED for b in PHASED] + [(a, b) for a in PHASED for b in UNPHASED]

    rows, excluded = [], []
    for i, (g1, g2) in enumerate(combos):
        name = f"o{i:03d}"
        try:
            apoe = call_apoe(g1, g2)
            a1, a2 = apoe
            dose = apoe_dose(a1, a2)
        except Exception as exc:  # the reference script raises on some inputs
            excluded.append((name, g1, g2, type(exc).__name__))
            continue
        if apoe == "..":
            call, doses = "NA", ["NA"] * 4
        else:
            call = f"ε{a1}/ε{a2}"
            doses = [str(dose[k]) for k in "1234"]
        rows.append((name, g1, g2, call, *doses))

    with open(os.path.join(DATA, "oracle_gt_combos_hg38.vcf"), "w", newline="\n") as fh:
        fh.write("##fileformat=VCFv4.2\n")
        fh.write('##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n')
        fh.write("##contig=<ID=chr19,length=58617616>\n")
        fh.write("\t".join(["#CHROM", "POS", "ID", "REF", "ALT", "QUAL", "FILTER", "INFO", "FORMAT"]
                           + [r[0] for r in rows]) + "\n")
        fh.write("\t".join(["chr19", "44908684", "rs429358", "T", "C", "100", "PASS", ".", "GT"]
                           + [r[1] for r in rows]) + "\n")
        fh.write("\t".join(["chr19", "44908822", "rs7412", "C", "T", "100", "PASS", ".", "GT"]
                           + [r[2] for r in rows]) + "\n")

    with open(os.path.join(DATA, "oracle_expected.tsv"), "w", newline="\n") as fh:
        fh.write("# Generated by tests/oracle/gen_oracle.py from apoe-genotyper.py callAPOE()/apoeDose().\n")
        for name, g1, g2, exc in excluded:
            fh.write(f"# excluded {name}: rs429358={g1} rs7412={g2} (reference script raised {exc})\n")
        fh.write("#sample\trs429358_gt\trs7412_gt\tAPOE\te1_dose\te2_dose\te3_dose\te4_dose\n")
        for r in rows:
            fh.write("\t".join(r) + "\n")

    print(f"{len(rows)} oracle samples, {len(excluded)} excluded", file=sys.stderr)


if __name__ == "__main__":
    main()
